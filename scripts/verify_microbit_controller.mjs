import {createRequire} from 'node:module';
import {createServer} from 'node:http';
import {readFile} from 'node:fs/promises';
import {resolve, extname} from 'node:path';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
const require=createRequire(import.meta.url);
const {chromium}=require('playwright');
const root=resolve('linux-elevhub/server/microbit-controller');
const server=createServer(async(req,res)=>{
  try{const name=new URL(req.url,'http://localhost').pathname;
    const file=resolve(root,'.'+(name==='/'?'/index.html':name));
    if(!file.startsWith(root+'/')&&!file.startsWith(root+'\\'))throw Error('path');
    res.setHeader('Content-Type',({'.js':'text/javascript','.css':'text/css','.html':'text/html'})[extname(file)]||'application/octet-stream');
    res.end(await readFile(file));
  }catch{res.writeHead(404);res.end();}
});
await new Promise(r=>server.listen(0,'127.0.0.1',r));
const browser=await chromium.launch({headless:true,channel:'chrome'});
const page=await browser.newPage();
page.on('pageerror',e=>console.log('PAGEERROR '+e.message));
page.on('requestfailed',r=>console.log('NETWORK '+r.url().slice(0,150)+' '+r.failure()?.errorText));
try{
  await page.goto(`http://127.0.0.1:${server.address().port}/`);
  await page.waitForFunction(()=>window.ElevhubProjectAdapter);
  await page.evaluate(()=>window.ElevhubProjectAdapter.reset());
  console.log('PASS live reset');
  await page.evaluate(()=>window.ElevhubProjectAdapter.setName('Integrationstest'));
  await page.evaluate(()=>window.ElevhubProjectAdapter.prepareSave());
  const baseline=await page.evaluate(async()=>JSON.parse(await(await window.ElevhubProjectAdapter.export()).text()));
  assert.equal(baseline.project.header.name,'Integrationstest');
  assert.ok(baseline.project.text['pxt.json']);
  const sample=structuredClone(baseline);
  sample.project.header.editor='tsprj'; sample.project.text['main.ts']='basic.showNumber(42)';
  sample.project.text['main.blocks']='';
  await page.evaluate(async value=>window.ElevhubProjectAdapter.import(new Blob([JSON.stringify(value)])),sample);
  await page.evaluate(()=>window.ElevhubProjectAdapter.prepareFinish());
  const saved=await page.evaluate(async()=>JSON.parse(await(await window.ElevhubProjectAdapter.export()).text()));
  assert.match(saved.project.text['main.ts'],/42/);
  console.log('PASS live name, import and flush capture editable source');
  const editor=page.frames().find(frame=>frame.url().startsWith('https://makecode.microbit.org/'));
  const code=editor.locator('.monaco-editor textarea').first();
  await code.press('Control+a'); await code.pressSequentially('basic.showNumber(88)',{delay:1});
  await page.evaluate(()=>window.ElevhubProjectAdapter.prepareFinish());
  assert.match(await page.evaluate(async()=>await(await window.ElevhubProjectAdapter.export()).text()),/showNumber\(88\)/);
  console.log('PASS immediate real editor typing is flushed before finish');
  await page.evaluate(()=>window.ElevhubProjectAdapter.reset());
  await page.evaluate(()=>window.ElevhubProjectAdapter.prepareSave());
  const blank=await page.evaluate(async()=>await(await window.ElevhubProjectAdapter.export()).text());
  assert.ok(!blank.includes('showNumber(42)'));
  await page.evaluate(async value=>window.ElevhubProjectAdapter.import(new Blob([JSON.stringify(value)])),saved);
  await page.evaluate(()=>window.ElevhubProjectAdapter.prepareSave());
  assert.match(await page.evaluate(async()=>await(await window.ElevhubProjectAdapter.export()).text()),/showNumber\(42\)/);
  console.log('PASS live reset and reopening preserve the saved program');
  const source=JSON.parse(execFileSync('python',['-c',"import sys,json; from pathlib import Path; sys.path.insert(0,'linux-elevhub/projekter'); from makecode_import import editable_project; print(json.dumps(editable_project(Path('linux-elevhub/tests/fixtures/makecode-source.hex').read_bytes())))"],{encoding:'utf8'}));
  await page.evaluate(async project=>window.ElevhubProjectAdapter.import(new Blob([JSON.stringify({format:'elevhub-microbit-project',type:'microbit',version:1,project})])),source);
  assert.match(await page.evaluate(async()=>await(await window.ElevhubProjectAdapter.export()).text()),/Elevhub-pilot/);
  console.log('PASS old HEX opens in the real guarded controller');
}finally{await browser.close();await new Promise(r=>server.close(r));}
