import Clipper from 'clipper-lib';
import {path,imageOutline,round,validPath} from './laser-geometry.js';

// Geometry is in millimetres. Integer clipping uses micrometres; curve and
// rounded-corner approximation each stays within 0.025 mm of its source.
const SCALE=1000,TOLERANCE=.025,MAX_POINTS=24000;
const TOO_COMPLEX='Figuren har for mange detaljer. Brug mere udglatning ved tracing, eller vælg færre figurer.';
function union(paths,fill=Clipper.PolyFillType.pftNonZero){
  const clipper=new Clipper.Clipper(),tree=new Clipper.PolyTree();
  clipper.StrictlySimple=true;
  clipper.AddPaths(paths,Clipper.PolyType.ptSubject,true);
  clipper.Execute(Clipper.ClipType.ctUnion,tree,fill,fill);
  return tree;
}
const contours=(tree,holes)=>holes?Clipper.Clipper.PolyTreeToPaths(tree):tree.Childs().map(node=>node.Contour());

export function offsetOutline(items,{distance=2,corners='round',holes=false}={}){
  if(!items.length)throw Error('Vælg en figur eller et tracet billede først.');
  if(!Number.isFinite(distance)||distance<.1||distance>30)throw Error('Vælg en afstand mellem 0,1 og 30 mm.');
  if(!['round','miter'].includes(corners))throw Error('Vælg runde eller skarpe hjørner.');
  let count=0;const closedPaths=[],openPaths=[];
  for(const item of items){
    const d=imageOutline(item);
    if(!d)throw Error(`Trace “${item.name}” først, så skærelinjen kan følge billedets form.`);
    const source=path(d),polygons=[];
    try{
      for(const contour of source.children){
        contour.flatten(TOLERANCE);
        count+=contour.segments.length;if(count>MAX_POINTS)throw Error(TOO_COMPLEX);
        const points=[];
        for(const s of contour.segments){
          const p={X:Math.round(s.point.x*SCALE),Y:Math.round(s.point.y*SCALE)},last=points.at(-1);
          if(!last||p.X!==last.X||p.Y!==last.Y)points.push(p);
        }
        if(contour.closed){if(points.length>=3)polygons.push(points);}
        else if(points.length>=2)openPaths.push(points);
      }
    }finally{source.remove();}
    if(polygons.length){
      // Resolve each object's fill rule separately, so overlapping objects do
      // not cancel under even-odd filling, and mirrored holes stay holes.
      const fill=item.image||item.fillRule==='evenodd'?Clipper.PolyFillType.pftEvenOdd:Clipper.PolyFillType.pftNonZero;
      closedPaths.push(...contours(union(polygons,fill),holes));
    }
  }
  const offset=new Clipper.ClipperOffset(2,TOLERANCE*SCALE);
  const join=corners==='round'?Clipper.JoinType.jtRound:Clipper.JoinType.jtMiter;
  if(closedPaths.length)offset.AddPaths(contours(union(closedPaths),holes),join,Clipper.EndType.etClosedPolygon);
  if(openPaths.length)offset.AddPaths(openPaths,join,Clipper.EndType.etOpenRound);
  const solution=[];offset.Execute(solution,distance*SCALE);
  // Merge touching offsets and discard enclosed contours for an outside-only
  // cut. Separate islands remain separate; we never invent connecting bridges.
  const result=contours(union(solution),holes).filter(p=>p.length>=3);
  if(!result.length)throw Error('Der kunne ikke dannes en skærelinje. Vælg en figur med tydelige konturer.');
  const d=result.map(points=>'M'+points.map(p=>`${round(p.X/SCALE)},${round(p.Y/SCALE)}`).join('L')+'Z').join('');
  if(!validPath(d))throw Error(TOO_COMPLEX);
  return {d,fillRule:'nonzero',contours:result.length,hasOpenPaths:!!openPaths.length};
}
