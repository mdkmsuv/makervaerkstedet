const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const start = fs.readFileSync(path.join(root, 'ansible/roles/kiosk/templates/start.html.j2'), 'utf8');
const creative = fs.readFileSync(path.join(root, 'server/elevhub/web/assets/creative-hub.js'), 'utf8');
assert.doesNotMatch(start, /OFFLINE_APPS|LOKALE_APP_URLER\.(microbit)|LOKALE_APP_URLER\['3dprint'\]/);
assert.match(start, /127\.0\.0\.1:8790\/apps/);
assert.match(start, /installeredeApps = \[\]; katalogKlar = false/);
assert.match(start, /local_start: app\.start/);
assert.match(start, /if \(app.local_start\) return adresse\(app\)/);
assert.match(start, /const INTERNET_APP = \{id: 'internet'/);
assert.match(start, /id="catalog-error"[^>]+role="alert"/);
assert.match(creative, /connection\(ok,offlineMode=false\)/);
assert.match(creative, /app\.requires_internet\s*\?\s*'Kræver internet'/);
console.log('kiosk installed offline catalog contract: ok');
